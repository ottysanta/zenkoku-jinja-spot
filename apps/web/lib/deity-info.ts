/** deity 文字列（例: "天照大御神、豊受大御神"）をパースして祭神情報を返す */
export function resolveDeities(deityField: string | null | undefined): DeityInfo[] {
  if (!deityField) return [];

  // 区切り文字で分割（読点・コンマ・中黒・改行・スラッシュ等）
  const names = deityField
    .split(/[、,・\n\/・〔〕【】「」『』（）()]+/)
    .map((s) => s.trim())
    .filter((s) => s.length > 0);

  const result: DeityInfo[] = [];
  const seen = new Set<string>();

  for (const name of names) {
    for (const deity of DEITY_DB) {
      if (seen.has(deity.name)) continue;
      const matched = deity.aliases.some(
        (alias) => name.includes(alias) || alias.includes(name),
      );
      if (matched) {
        result.push(deity);
        seen.add(deity.name);
        break;
      }
    }
  }

  return result;
}

